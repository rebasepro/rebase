/**
 * Bakes the site's Neat configuration into `src/data/neat-config.ts`.
 *
 * The gradient in this film is the REAL `@firecms/neat`, not an imitation of
 * it — so it has to run the real configuration too, and that configuration
 * lives in exactly one place: the marketing site's `NeatBackground.tsx`. Ninety
 * lines of camera, flow, texture and shape parameters are not something to
 * retype and hope; one drifted `planeTwist` and the film is showing a gradient
 * the website does not have.
 *
 * So it is copied mechanically, and re-copied by re-running this script.
 *
 * Re-run with `pnpm neat:config` whenever the site's gradient changes.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.resolve(here, "../../../website/src/components/NeatBackground.tsx");
const TARGET = path.resolve(here, "../src/data/neat-config.ts");

const src = fs.readFileSync(SOURCE, "utf8");

/** Brace-matched slice starting at the first `{` after `marker`. */
function objectAfter(marker) {
    const start = src.indexOf(marker);
    if (start === -1) throw new Error(`could not find ${marker} in ${SOURCE}`);
    const open = src.indexOf("{", start);
    let depth = 0;
    for (let i = open; i < src.length; i++) {
        if (src[i] === "{") depth++;
        else if (src[i] === "}") {
            depth--;
            if (depth === 0) return src.slice(open, i + 1);
        }
    }
    throw new Error(`unbalanced braces after ${marker}`);
}

// `as const` is a type assertion the emitted file does not want.
const base = objectAfter("const NEAT_BASE_CONFIG").replace(/ as const/g, "");

fs.writeFileSync(
    TARGET,
    `// GENERATED by scripts/extract-neat-config.mjs — do not edit by hand.
// Source: website/src/components/NeatBackground.tsx (NEAT_BASE_CONFIG).
//
// Everything the site's hero renders with, including the licence key.
//
// The key is not a secret and copying it here leaks nothing: Neat verifies it
// client-side (ECDSA P-256 over a payload naming the domain), so it already
// ships in the public JS bundle of rebase.pro and is readable with view-source.
// It is domain-locked to rebase.pro, and isDomainMatch() in the library allows
// localhost unconditionally — which is what a Remotion render is. An invalid or
// missing key does not fail the render; it draws a watermark into the canvas.
//
// One thing the site has that this does NOT: a seed. The site never sets one,
// so Neat falls back to "seconds elapsed in the current hour" and the animation
// starts at a different phase on every load. Harmless on a web page, fatal in a
// renderer. See NeatCanvas for how time is pinned instead.
//
// Note \`resolution: 0.05\`. That is MESH resolution, not pixel resolution:
// the ribbon geometry is built at \`240 * resolution\` segments a side, so 0.05
// means a 12x12 quad ribbon. The large flat facets ARE the geometry, which is
// why they stay crisp at any output size.

export const NEAT_BASE_CONFIG = ${base.trimEnd()} as const;
`,
);

const lines = base.split("\n").length;
console.log(`wrote NEAT_BASE_CONFIG (${lines} lines) to ${path.relative(process.cwd(), TARGET)}`);
