function writeToUiTs() {
  const fileContent = fs.readFileSync('website/src/i18n/ui.ts', 'utf8');
  
  const langs = ['en', 'es', 'de', 'fr'];
  const newStrings = { en: en_strings, es: es_strings, de: de_strings, fr: fr_strings };
  
  let newFileContent = fileContent;
  
  for (const lang of langs) {
    const stringEntries = Object.entries(newStrings[lang]).map(([k, v]) => `    '${k}': ${JSON.stringify(v)},`).join('\n');
    
    // Find where the lang block ends
    const regex = new RegExp(`^\\s+${lang}:\\s+\\{[\\s\\S]*?\\n\\s+\\},$`, 'm');
    const match = newFileContent.match(regex);
    if (!match) {
        // Maybe it's the last one without a comma
        const regex2 = new RegExp(`^\\s+${lang}:\\s+\\{[\\s\\S]*?\\n\\s+\\}$`, 'm');
        const match2 = newFileContent.match(regex2);
        if (match2) {
            const block = match2[0];
            const newBlock = block.replace(/\n\s+\}$/, `,\n${stringEntries}\n  }`);
            newFileContent = newFileContent.replace(block, newBlock);
        } else {
            console.log("Could not find lang block for", lang);
        }
    } else {
        const block = match[0];
        const newBlock = block.replace(/\n\s+\},$/, `,\n${stringEntries}\n  },`);
        newFileContent = newFileContent.replace(block, newBlock);
    }
  }
  
  fs.writeFileSync('website/src/i18n/ui.ts', newFileContent);
}

