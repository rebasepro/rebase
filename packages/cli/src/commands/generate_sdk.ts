/**
 * CLI command: generate-sdk
 *
 * Reads the project's tables — `backend/schema`, through the loader the
 * backend boots from, so the SDK describes exactly the tables served — or,
 * with `--from`, a running project's contract, and writes a typed TypeScript
 * SDK to the output directory (default: ./generated/sdk).
 */

import fs from "fs";
import path from "path";
import chalk from "chalk";
import { computeSchemaVersion, type TableDescriptor } from "@rebasepro/types";
import { CodegenError, generateSDK, GeneratedFile, toTableAccessor } from "@rebasepro/codegen";
import { isSchemaDefinitionError } from "@rebasepro/common";
import { findProjectRoot, readEnvFile } from "../utils/project";
import { DEV_BACKEND_URL_ENV } from "../utils/dev-server";
import { Refusal } from "../utils/refusal";
import { findBackendApp, GENERATED_DIR, loadManifest, manifestExists, writeManifest } from "../manifest";
import { readLink } from "./cloud/context";
import { SCHEMA_DIR_FLAG_HELP, PATH_RESOLUTION_RULE } from "../utils/path-flags";
import { loadProjectSchema, type ModuleAliases } from "../utils/project-schema";

interface GenerateSDKArgs {
    /** The schema directory: the one whose index exports the tables. */
    schemaDir: string;
    output: string;
    cwd: string;
    /**
     * Where to read the schema from instead of local source.
     *
     * `link` uses this checkout's linked project; anything else is treated as
     * the base URL of a Rebase backend. This is what lets a repository that
     * contains no tables — a separate frontend, a second web app — generate
     * a typed client from the project it talks to.
     */
    from?: string;
    /** Bearer token for the contract endpoint. Falls back to REBASE_SERVICE_KEY. */
    token?: string;
    /**
     * Also register the generated `Database` for server-side code: write the
     * types and the `Register` augmentation into `backend/generated/`. See
     * {@link writeRegistration}.
     */
    register?: boolean;
    /**
     * The directory holding `rebase.json`, where `--register` is remembered
     * and under which `backend/generated/` is. Found from `cwd` when not given.
     */
    projectRoot?: string;
    /** Module specifiers mapped to files when importing the schema (in-repo runs and tests). */
    moduleAliases?: ModuleAliases;
    help?: boolean;
}

/** What `--register` writes, and what marks a project as having opted in. */
export const REGISTER_FILE = "register.ts";

/** The first line of {@link REGISTER_FILE}: a file without it is the developer's own. */
const REGISTER_MARKER = "// Auto-generated by `rebase generate-sdk --register`. Do not edit.";

const REGISTER_SOURCE = `${REGISTER_MARKER}
//
// Registers this project's generated \`Database\` on \`@rebasepro/types\`, so
// \`context.data\` in table hooks, \`rebase.dataAsAdmin\`, and the
// \`rebase\` a function or a cron receives are typed from it. Every later
// \`rebase generate-sdk\` (and \`rebase dev\`) refreshes this directory; delete
// it to go back to untyped server-side data.
import type { Database } from "./database.types";

declare module "@rebasepro/types" {
    interface Register {
        database: Database;
    }
}
`;

/**
 * Where `--register` writes: `backend/generated/` under the project root.
 *
 * Inside `backend/` because that is the program the hooks, functions and
 * crons it types are compiled in. The types are copied in beside the
 * registration rather than imported from `generated/sdk`, which is outside
 * the backend's `rootDir`.
 */
export function registrationDir(projectRoot: string): string {
    return path.join(projectRoot, GENERATED_DIR);
}

/** Whether this project opted in: the registration is there, and it is ours. */
function hasRegistration(dir: string): boolean {
    try {
        return fs.readFileSync(path.join(dir, REGISTER_FILE), "utf-8").startsWith(REGISTER_MARKER);
    } catch {
        return false;
    }
}

/** Write a file only when its content changed, so a watcher on the directory does not restart for nothing. */
function writeIfChanged(filePath: string, content: string): void {
    try {
        if (fs.readFileSync(filePath, "utf-8") === content) return;
    } catch {
        // Not there yet.
    }
    fs.writeFileSync(filePath, content, "utf-8");
}

/**
 * Write the generated `Database` and its `Register` augmentation into
 * {@link registrationDir}. Refuses to overwrite a `register.ts` it did not
 * write.
 */
function writeRegistration(dir: string, databaseTypes: string): void {
    const registerPath = path.join(dir, REGISTER_FILE);
    if (fs.existsSync(registerPath) && !hasRegistration(dir)) {
        throw new Error(
            `${registerPath} exists and was not written by "rebase generate-sdk --register". ` +
            "Move it, or register the Database there yourself."
        );
    }
    fs.mkdirSync(dir, { recursive: true });
    writeIfChanged(path.join(dir, "database.types.ts"), databaseTypes);
    writeIfChanged(registerPath, REGISTER_SOURCE);
}

/**
 * Write the server-side registration from the build's tables, exactly as
 * `rebase generate-sdk` writes it.
 *
 * Only for a project that asked for it: `registerDatabase` in `rebase.json`,
 * or a registration an earlier `--register` left, which is kept current. The
 * registration lives in gitignored `backend/generated/`, so a fresh clone (a
 * CI job) has none until something writes it, and a bundle compiled without
 * it types `context.data` as untyped rows: hooks that read a typed column fail
 * to compile there while they compile locally.
 *
 * Returns the directory written, or null when there was nothing to do.
 * Throws when a `register.ts` there is not ours, as `generate-sdk` refuses.
 */
export async function writeRegistrationForBuild(
    projectRoot: string,
    tables: readonly TableDescriptor[],
    registerDatabase: boolean
): Promise<string | null> {
    const dir = registrationDir(projectRoot);
    if (!registerDatabase && !hasRegistration(dir)) return null;
    if (tables.length === 0) return null;
    const databaseTypes = generateSDK(sortedBySlug(tables), { includeReadme: false })
        .find((file) => file.path === "database.types.ts")?.content;
    if (databaseTypes === undefined) return null;
    writeRegistration(dir, databaseTypes);
    return dir;
}

/** Tables sorted by slug: the same schema generates the same bytes, whatever order the index lists it in. */
function sortedBySlug(tables: readonly TableDescriptor[]): TableDescriptor[] {
    return [...tables].sort((a, b) => a.slug.localeCompare(b.slug));
}

/**
 * Whether `rebase.json` asks for the registration (`registerDatabase: true` on
 * the backend app). That is what survives a clone: `generated/` is gitignored,
 * so a `register.ts` from an earlier run is not there to say it.
 *
 * An unreadable manifest answers no; `rebase build` is where it is reported.
 */
function manifestRegisters(projectRoot: string | undefined): boolean {
    if (!projectRoot || !manifestExists(projectRoot)) return false;
    try {
        return findBackendApp(loadManifest(projectRoot).manifest)?.app.registerDatabase === true;
    } catch {
        return false;
    }
}

/**
 * Remember `--register` in `rebase.json`, so later runs, `rebase dev` and a
 * fresh clone keep registering. Returns where it was written, or why not.
 *
 * Never creates the file: a project without one is synthesized from its
 * layout, and writing one is `rebase apps init`'s decision, not this flag's.
 */
function rememberRegistration(projectRoot: string | undefined): { written: string } | { skipped: string } {
    if (!projectRoot || !manifestExists(projectRoot)) {
        return { skipped: "No rebase.json here, so the choice lasts as long as the generated files." };
    }
    let loaded: ReturnType<typeof loadManifest>;
    try {
        loaded = loadManifest(projectRoot);
    } catch (error) {
        return { skipped: `rebase.json could not be read (${error instanceof Error ? error.message : String(error)}).` };
    }
    const backend = findBackendApp(loaded.manifest);
    if (!backend) return { skipped: "rebase.json declares no backend app to remember it on." };
    if (backend.app.registerDatabase === true) return { written: loaded.filePath ?? projectRoot };
    const manifest = {
        ...loaded.manifest,
        apps: { ...loaded.manifest.apps, [backend.name]: { ...backend.app, registerDatabase: true } }
    };
    return { written: writeManifest(projectRoot, manifest) };
}

/**
 * The tables the backend serves, read the way it reads them: the schema
 * directory's index, through `loadBackendSchema`, compiled to descriptors.
 *
 * A definition the backend would refuse is fatal here too, as it is at boot:
 * `rebase dev` runs this on every save, and skipping a table would overwrite
 * good types with a `Database` that is silently short one. A missing
 * directory is a `Refusal`: the message says all there is. A module that
 * throws on import is not: that is the project's own code failing, and the
 * stack `--debug` prints points at the line.
 */
async function loadTables(projectRoot: string, schemaDir: string, aliases?: ModuleAliases): Promise<TableDescriptor[]> {
    const absDir = path.resolve(schemaDir);
    if (!fs.existsSync(absDir)) {
        throw new Refusal(`Schema directory not found: ${absDir} (${PATH_RESOLUTION_RULE})`);
    }
    const { compiled } = await loadProjectSchema(projectRoot, absDir, aliases);
    return compiled.descriptors;
}

/**
 * Write generated files to the output directory.
 */
function writeFiles(outputDir: string, files: GeneratedFile[]): void {
    const absOutput = path.resolve(outputDir);

    // Create output directory
    fs.mkdirSync(absOutput, { recursive: true });

    for (const file of files) {
        const filePath = path.join(absOutput, file.path);
        const dir = path.dirname(filePath);
        if (!fs.existsSync(dir)) {
            fs.mkdirSync(dir, { recursive: true });
        }
        fs.writeFileSync(filePath, file.content, "utf-8");
    }
}

