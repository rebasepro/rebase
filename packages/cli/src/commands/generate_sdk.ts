/** What `--from` sent to the contract endpoint, and which keys it left behind. */
interface ContractCredential {
    /** The bearer token sent: `--token`, the shell's key, or none. */
    sent: "token" | "ambient" | null;
    /** `REBASE_SERVICE_KEY` is in the shell environment. */
    shellKey: boolean;
    /** `REBASE_SERVICE_KEY` is in the project's `.env`. */
    envFileKey: boolean;
}

/**
 * What to say when the contract endpoint refuses, by what was and was not sent.
 *
 * "Set REBASE_SERVICE_KEY" is only right when no key exists. The shell's key is
 * withheld from every host but the linked project, and `.env`'s is never read
 * here — it is the local backend's key, and the linked project is usually a
 * deployed one — so telling a reader whose key is in `.env` to set it sends them
 * to fix something that is not broken.
 */
function contractRefusalHint(credential: ContractCredential): string[] {
    if (credential.sent === "token") {
        return ["The token passed with --token was refused: pass a service key, or an admin's token."];
    }
    if (credential.sent === "ambient") {
        return ["REBASE_SERVICE_KEY was sent and refused: it is not this project's service key. Pass the right one with --token."];
    }
    if (credential.shellKey) {
        return [
            "REBASE_SERVICE_KEY is set, but it is only sent to this checkout's linked project, and this host is not it.",
            "Pass the key with --token to send it here."
        ];
    }
    if (credential.envFileKey) {
        return [
            "REBASE_SERVICE_KEY in .env is not sent: --from sends the shell's REBASE_SERVICE_KEY, and only to this checkout's linked project.",
            "Pass the key with --token."
        ];
    }
    return ["Pass --token <key>, a service key or an admin's token. The shell's REBASE_SERVICE_KEY is sent only to this checkout's linked project."];
}

/**
 * Whether one entry of a contract's `tables` is a table descriptor, as far as
 * the generator reads one: a slug, a SQL name, columns and relations.
 */
function isTableDescriptor(value: unknown): value is TableDescriptor {
    return typeof value === "object" && value !== null
        && "slug" in value && typeof value.slug === "string"
        && "table" in value && typeof value.table === "string"
        && "columns" in value && Array.isArray(value.columns)
        && "relations" in value && Array.isArray(value.relations);
}

/**
 * The tables a running project serves, from its contract endpoint
 * (`{ schemaVersion, runtime, tables: TableDescriptor[] }`). The descriptors
 * are plain data — no thunks to rehydrate — so they go to the generator as
 * they arrive.
 */
async function fetchRemoteTables(
    baseUrl: string,
    token: string | undefined,
    credential: ContractCredential
): Promise<{ tables: TableDescriptor[]; schemaVersion: string }> {
    const url = `${baseUrl.replace(/\/+$/, "")}/api/meta/contract`;

    const headers: Record<string, string> = { accept: "application/json" };
    if (token) headers.authorization = `Bearer ${token}`;

    let response: Response;
    try {
        response = await fetch(url, { headers });
    } catch (err) {
        console.log(chalk.red(`  ✗ Could not reach ${url}`));
        console.log(chalk.gray(`    ${err instanceof Error ? err.message : String(err)}`));
        process.exit(1);
    }

    if (response.status === 401 || response.status === 403) {
        console.log(chalk.red(`  ✗ Not authorized to read the project contract (${response.status}).`));
        console.log(chalk.gray("    The contract describes every table and relation, so it is admin-only."));
        for (const line of contractRefusalHint(credential)) console.log(chalk.gray(`    ${line}`));
        process.exit(1);
    }

    if (response.status === 404) {
        console.log(chalk.red("  ✗ This server has no contract endpoint."));
        console.log(chalk.gray("    It needs to be running Rebase 0.11 or newer."));
        process.exit(1);
    }

    if (!response.ok) {
        console.log(chalk.red(`  ✗ Contract request failed with ${response.status}.`));
        process.exit(1);
    }

    const contract: unknown = await response.json();
    const field = (key: string): unknown =>
        typeof contract === "object" && contract !== null && key in contract
            ? Object.entries(contract).find(([name]) => name === key)?.[1]
            : undefined;
    const tables = field("tables");
    const schemaVersion = field("schemaVersion");

    if (!Array.isArray(tables)) {
        if (Array.isArray(field("collections"))) {
            // A server from before tables: its contract lists collections, a
            // shape this CLI no longer generates from.
            console.log(chalk.red("  ✗ This server answers the contract with collections: it runs a Rebase release from before tables."));
            console.log(chalk.gray("    Upgrade the server to a release that serves `tables`, or generate from this project's"));
            console.log(chalk.gray("    own backend/schema by running `rebase generate-sdk` without --from."));
            process.exit(1);
        }
        console.log(chalk.red("  ✗ The contract response did not contain tables."));
        process.exit(1);
    }
    const invalid = tables.findIndex(entry => !isTableDescriptor(entry));
    if (invalid !== -1) {
        console.log(chalk.red(`  ✗ The contract's tables[${invalid}] is not a table descriptor (no slug, table, columns or relations).`));
        process.exit(1);
    }

    return {
        tables: tables.filter(isTableDescriptor),
        schemaVersion: typeof schemaVersion === "string" ? schemaVersion : "unknown"
    };
}

/**
 * Decide whether the ambient service key may be sent to this host.
 *
 * `REBASE_SERVICE_KEY` grants full admin bypass. Attaching it to whatever URL
 * happened to be passed — or, worse, to whatever a committed `.rebase/cloud.json`
 * points at — would hand the project's most powerful credential to a host nobody
 * vetted. An explicit `--token` is a decision the caller made; the ambient
 * variable is not, so it only travels to the project this checkout is linked to.
 */
function mayUseAmbientKey(target: string, cwd: string): boolean {
    const link = readLink(findProjectRoot(cwd) ?? cwd);
    if (!link?.apiUrl) return false;
    try {
        // Origin, not host: with a link recorded as https, an `http://` target
        // for the same host would otherwise pass and send the key in cleartext.
        return new URL(link.apiUrl).origin === new URL(target).origin;
    } catch {
        return false;
    }
}

/**
 * The base URL to show in the printed usage example.
 *
 * `rebase dev` binds a port derived from the project path, not 3001, and writes
 * the one it actually got to `.rebase/state.json`. Printing a hardcoded
 * `localhost:3001` sent people to a port nothing was listening on — or, with
 * several projects on one machine, to a different project's backend. Prefer the
 * port `rebase dev` says it is starting the backend on (`DEV_BACKEND_URL_ENV`:
 * it regenerates the SDK before the backend binds), then the port this project
 * last ran on; fall back to the literal only when the project has never been
 * started.
 */
export function resolveExampleBaseUrl(cwd: string): string {
    const fromDev = process.env[DEV_BACKEND_URL_ENV]?.trim();
    if (fromDev) return fromDev;
    const projectRoot = findProjectRoot(cwd) ?? cwd;
    try {
        const state = JSON.parse(fs.readFileSync(path.join(projectRoot, ".rebase", "state.json"), "utf-8"));
        if (typeof state.baseUrl === "string" && state.baseUrl) return state.baseUrl;
        if (typeof state.port === "number") return `http://localhost:${state.port}`;
    } catch {
        // Never started, or the file is unreadable — fall through.
    }
    return "http://localhost:3001";
}

/** Whether a slug can be written as `rebase.data.<slug>` rather than a lookup. */
export function isIdentifierLike(slug: string): boolean {
    return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(slug);
}

/** Resolve `--from` into a base URL, following the link file when asked. */
function resolveSchemaSource(from: string, cwd: string): string {
    if (from !== "link") {
        // A bare hostname or a typo would otherwise be handed to `fetch` and fail
        // with something unhelpful; a non-http scheme has no business here at all.
        let parsed: URL;
        try {
            parsed = new URL(from);
        } catch {
            console.log(chalk.red(`  ✗ "${from}" is not a valid URL.`));
            console.log(chalk.gray("    Pass a full URL, e.g. https://api.example.com, or \"link\"."));
            process.exit(1);
        }
        if (parsed.protocol !== "http:" && parsed.protocol !== "https:") {
            console.log(chalk.red("  ✗ The project URL must be http or https."));
            process.exit(1);
        }
        return from;
    }

    const projectRoot = findProjectRoot(cwd) ?? cwd;
    const link = readLink(projectRoot);

    if (!link) {
        console.log(chalk.red("  ✗ This checkout is not linked to a project."));
        console.log(chalk.gray("    Run `rebase cloud link <url>`, or pass --from <url>."));
        process.exit(1);
    }

    const apiUrl = link.apiUrl;
    if (!apiUrl) {
        console.log(chalk.red("  ✗ The project link has no API URL."));
        console.log(chalk.gray("    Re-link with `rebase cloud link <url>` to record one."));
        process.exit(1);
    }

    return apiUrl;
}

/**
 * Main entry point for the generate-sdk command.
 */
export async function generateSdkCommand(args: GenerateSDKArgs): Promise<void> {
    const { schemaDir, output, cwd } = args;

    if (args.help) {
        printSdkHelp();
        return;
    }

    const resolvedSchemaDir = path.isAbsolute(schemaDir)
        ? schemaDir
        : path.join(cwd, schemaDir);
    const projectRoot = args.projectRoot ?? findProjectRoot(cwd) ?? undefined;

    const resolvedOutput = path.isAbsolute(output)
        ? output
        : path.join(cwd, output);

    console.log("");
    console.log(chalk.bold("  🔧 Rebase SDK Generator"));
    console.log("");

    let tables: TableDescriptor[];
    let remoteSchemaVersion: string | undefined;

    if (args.from) {
        const baseUrl = resolveSchemaSource(args.from, cwd);
        console.log(`  ${chalk.gray("Project:")}     ${baseUrl}`);
        console.log(`  ${chalk.gray("Output:")}      ${resolvedOutput}`);
        console.log("");
        console.log(chalk.cyan("  → Fetching the project contract..."));

        const ambient = mayUseAmbientKey(baseUrl, cwd)
            ? process.env.REBASE_SERVICE_KEY
            : undefined;

        if (!args.token && !ambient && process.env.REBASE_SERVICE_KEY) {
            console.log(chalk.dim(
                "  (not sending REBASE_SERVICE_KEY — this host is not the linked project; pass --token to override)"
            ));
        }

        const remote = await fetchRemoteTables(baseUrl, args.token || ambient, {
            sent: args.token ? "token" : ambient ? "ambient" : null,
            shellKey: Boolean(process.env.REBASE_SERVICE_KEY),
            envFileKey: Boolean(readEnvFile(findProjectRoot(cwd) ?? cwd).REBASE_SERVICE_KEY)
        });
        tables = remote.tables;
        remoteSchemaVersion = remote.schemaVersion;
    } else {
        // A headless project has no schema directory by design: its API is
        // introspected from the live database at boot, and there is nothing here
        // to generate a client from. The scaffold ships `pnpm generate:sdk`
        // anyway, so the documented headless path had a script that could only
        // ever fail — and it failed with a path, which reads as a broken install
        // rather than a question with an answer.
        if (!fs.existsSync(resolvedSchemaDir)) {
            console.log(chalk.gray(
                "  ○ This project derives its API from the database — "
                + "there is no backend/schema to generate a client from."
            ));
            console.log(chalk.gray(
                `    Nothing to generate from: ${resolvedSchemaDir} does not exist.`
            ));
            console.log("");
            return;
        }
        console.log(`  ${chalk.gray("Schema:")}      ${resolvedSchemaDir}`);
        console.log(`  ${chalk.gray("Output:")}      ${resolvedOutput}`);
        console.log("");
        console.log(chalk.cyan("  → Loading the tables..."));
        try {
            tables = await loadTables(projectRoot ?? cwd, resolvedSchemaDir, args.moduleAliases);
        } catch (err) {
            // A definition the backend would refuse to boot on: every problem,
            // one per line, each naming its table.
            if (isSchemaDefinitionError(err)) {
                console.log("");
                console.log(chalk.red(`  ✗ ${err.message}`));
                process.exit(1);
            }
            throw err;
        }
    }

    // Sorted by slug, so the same schema generates the same SDK.
    tables = sortedBySlug(tables);

    if (tables.length === 0) {
        console.log(chalk.red("  ✗ No tables found. Nothing to generate."));
        process.exit(1);
    }

    console.log(chalk.green(`  ✓ Found ${tables.length} table(s): ${tables.map(table => table.slug).join(", ")}`));
    console.log("");

    // 2. Generate SDK files
    console.log(chalk.cyan("  → Generating SDK files..."));
    let files: GeneratedFile[];
    try {
        files = generateSDK(tables, { baseUrl: resolveExampleBaseUrl(cwd) });
    } catch (err) {
        // A schema that cannot be expressed as valid TypeScript — two slugs
        // that collide on one accessor, a slug with no usable name. The
        // generator refuses rather than emitting a file that does not compile,
        // or one that silently routes a table's reads to another's.
        if (err instanceof CodegenError) {
            console.log("");
            console.log(chalk.red(`  ✗ ${err.message}`));
            process.exit(1);
        }
        throw err;
    }

    // Stamp the schema this SDK was built from.
    //
    // Without it, an app in a separate repository has no way to know its client
    // is stale: the backend moves on, the frontend keeps compiling against types
    // captured weeks ago, and the mismatch only surfaces as a runtime error. With
    // it, CI can compare against `/api/meta/schema-version` and say so.
    //
    // No generation timestamp. Tables are sorted above precisely so that
    // the same schema produces the same bytes; a timestamp put that back,
    // turning every regeneration into a diff and making the obvious staleness
    // gate — `rebase generate-sdk && git diff --exit-code` — impossible to pass.
    // `SCHEMA_VERSION` already identifies what this was built from, and does it
    // in a way that can be compared against a running project.
    const schemaVersion = remoteSchemaVersion ?? computeSchemaVersion(tables);
    files.push({
        path: "schema.meta.ts",
        content: `// Auto-generated by \`rebase generate-sdk\`. Do not edit.
//
// The schema version this SDK was generated from. Compare it against the
// project's current version to detect drift:
//
//     curl -s <api-url>/api/meta/schema-version
//
// Pass it to the client as \`schemaVersion\` and every request carries it in
// the \`x-rebase-schema\` header, so the server can name the drift instead of
// answering a renamed field with a bare 400.
export const SCHEMA_VERSION = ${JSON.stringify(schemaVersion)};
`
    });

    console.log(chalk.green(`  ✓ Generated ${files.length} file(s)`));
    console.log(chalk.gray(`    schema ${schemaVersion}`));

    // 3. Write to disk
    console.log(chalk.cyan(`  → Writing to ${resolvedOutput}...`));
    writeFiles(resolvedOutput, files);

    // 4. The server-side registration: on request, and kept current once a
    // project has it, so `rebase dev` regenerating the SDK never leaves the
    // server typed against an older schema than the client.
    const registerDir = projectRoot ? registrationDir(projectRoot) : undefined;
    if (args.register || (registerDir && hasRegistration(registerDir)) || manifestRegisters(projectRoot)) {
        if (!registerDir || !fs.existsSync(path.dirname(registerDir))) {
            console.log(chalk.red(`  ✗ No backend/ directory to register the Database in${registerDir ? ` (${path.dirname(registerDir)})` : ""}.`));
            console.log(chalk.gray("    --register writes backend/generated/register.ts; run it inside a project with a backend."));
            process.exit(1);
            return;
        }
        const databaseTypes = files.find((file) => file.path === "database.types.ts")?.content;
        if (databaseTypes !== undefined) {
            try {
                writeRegistration(registerDir, databaseTypes);
            } catch (error) {
                console.log(chalk.red(`  ✗ ${error instanceof Error ? error.message : String(error)}`));
                process.exit(1);
                return;
            }
            console.log(chalk.green(`  ✓ Registered the Database for server-side code in ${registerDir}`));
            if (args.register) {
                const remembered = rememberRegistration(projectRoot);
                if ("written" in remembered) {
                    console.log(chalk.gray(`    Remembered in ${path.relative(cwd, remembered.written) || "rebase.json"} (registerDatabase).`));
                } else {
                    console.log(chalk.yellow(`    ${remembered.skipped}`));
                }
            }
        }
    }

    console.log("");
    console.log(chalk.green.bold("  ✓ SDK generated successfully!"));
    console.log("");
    const typesImport = `./${path.relative(cwd, path.join(resolvedOutput, "database.types"))}`;
    const metaImport = `./${path.relative(cwd, path.join(resolvedOutput, "schema.meta"))}`;
    const exampleSlug = tables[0]?.slug || "my_table";

    console.log(chalk.gray("  Usage:"));
    console.log(chalk.gray("    import { createRebaseClient } from '@rebasepro/client';"));
    console.log(chalk.gray(`    import { tablesDictionary, type Database } from '${typesImport}';`));
    console.log(chalk.gray(`    import { SCHEMA_VERSION } from '${metaImport}';`));
    console.log("");
    console.log(chalk.gray("    const rebase = createRebaseClient<Database>({"));
    console.log(chalk.gray(`        baseUrl: '${resolveExampleBaseUrl(cwd)}',`));
    // Sent as `x-rebase-schema` on every request. Costs one line here and is
    // the difference between a server that can say "this client is three
    // deploys behind" and one that can only reject a field it does not know.
    console.log(chalk.gray("        schemaVersion: SCHEMA_VERSION,"));
    // Without the dictionary a hyphenated slug is not resolvable from the
    // property name alone, and the request 404s at runtime.
    console.log(chalk.gray("        tables: tablesDictionary,"));
    console.log(chalk.gray("        // token: 'your-jwt-token',"));
    console.log(chalk.gray("    });"));
    console.log("");
    // `rebase.data.<accessor>` is the typed surface, so it is what gets printed.
    // `rebase.data.table(slug)` exists too, but it is generic over
    // `Record<string, unknown>` and has no link to `Database` — it was the
    // headline example here for a while, which advertised the one call shape
    // that throws away the types this command just generated.
    const exampleAccessor = toTableAccessor(exampleSlug);
    const exampleAccess = isIdentifierLike(exampleAccessor)
        ? `rebase.data.${exampleAccessor}`
        : `rebase.data[${JSON.stringify(exampleAccessor)}]`;
    console.log(chalk.gray(`    const { data } = await ${exampleAccess}.find();`));
    console.log("");
}
