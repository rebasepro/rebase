/**
 * Everything a copy is made of, in a form two databases can be compared by:
 * the tables and the md5 of each one's rows, the sequences' positions, and
 * the schema around them. Read in one transaction with the settings that
 * decide how values print set the same on both, and set LOCAL, so nothing is
 * left behind on PGlite's single session.
 */
async function fingerprint(connectionString: string): Promise<Record<string, unknown>> {
    const client = new pg.Client({ connectionString, connectionTimeoutMillis: 10_000, query_timeout: 30_000 });
    client.on("error", () => undefined);
    await client.connect();
    try {
        await client.query("BEGIN");
        await client.query("SET LOCAL TimeZone = 'UTC'");
        await client.query("SET LOCAL DateStyle = 'ISO, MDY'");
        await client.query("SET LOCAL extra_float_digits = 1");
        await client.query("SET LOCAL bytea_output = 'hex'");
        await client.query("SET LOCAL search_path = public");
        // As the owner, past RLS: the copy is what is compared, not what a policy shows.
        await client.query("SET LOCAL row_security = off");
        const tables = (await client.query<{ name: string }>(`
            SELECT format('%I.%I', table_schema, table_name) AS name FROM information_schema.tables
             WHERE table_type = 'BASE TABLE' AND table_schema NOT IN ('pg_catalog', 'information_schema')
             ORDER BY 1`)).rows.map(row => row.name);
        const rows: Record<string, string> = {};
        for (const table of tables) {
            const { rows: [result] } = await client.query<{ count: number; digest: string }>(
                `SELECT count(*)::int AS count, md5(coalesce(string_agg(t::text, E'\\n' ORDER BY t::text), '')) AS digest FROM ${table} AS t`
            );
            rows[table] = `${result.count}:${result.digest}`;
        }
        const list = async (text: string): Promise<string[]> =>
            (await client.query<{ item: string }>(text)).rows.map(row => row.item);
        const user = "NOT IN ('pg_catalog', 'information_schema', 'pg_toast')";
        const fingerprinted = {
            tables,
            rows,
            sequences: await list("SELECT format('%s.%s=%s', schemaname, sequencename, last_value) AS item FROM pg_sequences ORDER BY 1"),
            policies: await list("SELECT format('%s.%s.%s %s %s %s', schemaname, tablename, policyname, cmd, qual, with_check) AS item FROM pg_policies ORDER BY 1"),
            rls: await list(`SELECT format('%s rls=%s force=%s', c.oid::regclass, c.relrowsecurity, c.relforcerowsecurity) AS item
                               FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                              WHERE c.relkind = 'r' AND n.nspname ${user} ORDER BY 1`),
            triggers: await list("SELECT format('%s %s', tgrelid::regclass, tgname) AS item FROM pg_trigger WHERE NOT tgisinternal ORDER BY 1"),
            functions: await list(`SELECT format('%s.%s', n.nspname, p.proname) AS item FROM pg_proc p
                                     JOIN pg_namespace n ON n.oid = p.pronamespace
                                    WHERE n.nspname ${user} AND NOT EXISTS (
                                          SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
                                    ORDER BY 1`),
            constraints: await list(`SELECT format('%s %s %s', conrelid::regclass, conname, pg_get_constraintdef(oid)) AS item
                                       FROM pg_constraint WHERE connamespace::regnamespace::text ${user} AND conrelid <> 0 ORDER BY 1`),
            indexes: await list(`SELECT indexdef AS item FROM pg_indexes WHERE schemaname ${user} ORDER BY 1`),
            types: await list(`SELECT format('%s.%s', n.nspname, t.typname) AS item FROM pg_type t
                                 JOIN pg_namespace n ON n.oid = t.typnamespace
                                WHERE t.typtype = 'e' AND n.nspname ${user} ORDER BY 1`),
            views: await list(`SELECT format('%s.%s', schemaname, viewname) AS item FROM pg_views WHERE schemaname ${user} ORDER BY 1`),
            extensions: await list("SELECT extname AS item FROM pg_extension ORDER BY 1")
        };
        await client.query("COMMIT");
        return fingerprinted;
    } finally {
        await client.end().catch(() => undefined);
    }
}

/** The settings a session has changed for itself — on PGlite, for every connection there is. */
async function sessionSettings(connectionString: string): Promise<string[]> {
    const { rows } = await sql(connectionString, "SELECT name FROM pg_settings WHERE source = 'session' ORDER BY 1");
    return rows.map(row => String(row.name));
}

beforeAll(async () => {
    const image = await imageForLocalClient();
    process.once("exit", () => spawnSync("docker", ["rm", "-f", "-v", container], { stdio: "ignore" }));
    await execa("docker", [
        "run", "--rm", "-d", "--name", container,
        "-e", "POSTGRES_USER=rebase", "-e", "POSTGRES_PASSWORD=rebase", "-e", "POSTGRES_DB=rebase",
        "-p", "127.0.0.1::5432", image
    ]);
    const { stdout } = await execa("docker", ["port", container, "5432"]);
    port = /:(\d+)\s*$/m.exec(stdout)?.[1] ?? "";
    if (!port) throw new Error(`No published port in: ${stdout}`);

    // Ready means a query answers, not that the port listens: the image
    // restarts once during initialisation.
    for (let attempt = 0; ; attempt += 1) {
        try {
            await sql(url("rebase"), "SELECT 1");
            break;
        } catch (error) {
            if (attempt > 60) throw error;
            await new Promise(resolve => setTimeout(resolve, 500));
        }
    }
    await sql(url("rebase"), "CREATE DATABASE source");
    await sql(url("source"), SOURCE);

    work = fs.mkdtempSync(path.join(os.tmpdir(), "rebase-pull-managed-it-"));
    project = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rebase-pull-managed-project-")));
    managed = (await ensureManagedDatabase(project, { entry: CLI_ENTRY, quiet: true })).url;
}, 180_000);

afterAll(async () => {
    if (project) {
        await stopManagedDatabase(project).catch(() => undefined);
        fs.rmSync(project, { recursive: true, force: true });
    }
    if (work) fs.rmSync(work, { recursive: true, force: true });
    await execa("docker", ["rm", "-f", "-v", container], { reject: false });
});

/** A whole-database pull of the source into `target`, the steps `rebase db pull` takes. */
async function pullInto(target: string, name: string) {
    const dumpFile = path.join(work, `${name}.dump`);
    const dumped = await dumpSource({ source: url("source"), target, anonymize: false, schemas: [] }, dumpFile);
    if (!dumped.ok) throw new Error(dumped.lines.join("\n"));
    return restoreCopy(dumped.plan, dumpFile);
}

describe("rebase db pull into the managed database", () => {
    it("makes the copy a pull into Postgres makes", async () => {
        await sql(url("rebase"), "CREATE DATABASE postgres_copy");
        await sql(url("postgres_copy"), LOCAL);
        await sql(managed, LOCAL);

        const intoPostgres = await pullInto(url("postgres_copy"), "postgres");
        expect(intoPostgres).toEqual({ cleared: true, started: true, failure: null, advice: null });

        const intoManaged = await pullInto(managed, "managed");
        expect(intoManaged).toEqual({ cleared: true, started: true, failure: null, advice: null });

        const expected = await fingerprint(url("postgres_copy"));
        // The source itself, so the comparison is with what was pulled and
        // not with two copies that lost the same thing.
        expect(expected).toEqual(await fingerprint(url("source")));
        expect(await fingerprint(managed)).toEqual(expected);
    });

    it("leaves the managed database answering, with no session settings of the restore's left on it", async () => {
        // PGlite is one session for every connection, so what pg_restore SETs
        // for itself — search_path = '', row_security = off — would otherwise
        // stay on for the dev server's queries after the pull.
        expect((await sql(managed, "SELECT 1 AS ok")).rows).toEqual([{ ok: 1 }]);
        expect(await sessionSettings(managed)).toEqual([]);
    });

    it("succeeds the second time too", async () => {
        expect((await pullInto(managed, "again")).failure).toBeNull();
        expect((await sql(managed, "SELECT count(*)::int AS n FROM public.events")).rows).toEqual([{ n: 2345 }]);
    });

    it("refuses a dump whose rows are COPY data, and leaves the copy it has", async () => {
        // What restoring one did: the first COPY failed, and the daemon never
        // answered again. Refused before anything is emptied instead.
        const plan: PullPlan = { source: url("source"), target: managed, anonymize: false, schemas: [] };
        const dumpFile = path.join(work, "copy.dump");
        await execa("pg_dump", [...dumpArgs(plan), "--file", dumpFile], { env: dumpEnv(plan) });

        const outcome = await restoreCopy(plan, dumpFile);

        expect(outcome).toMatchObject({ cleared: false, started: false });
        expect(outcome.failure).toContain("COPY");
        expect(outcome.advice).toContain("rebase db pull --docker");
        expect((await sql(managed, "SELECT count(*)::int AS n FROM public.events")).rows).toEqual([{ n: 2345 }]);
    });
});

describe("dumpSource", () => {
    it("reports a source it cannot reach in the banner, and reads nothing", async () => {
        const closed = await findFreePort();
        const dumpFile = path.join(work, "unreachable.dump");

        const outcome = await dumpSource({
            source: `postgresql://rebase:s3cret@127.0.0.1:${closed}/rebase?sslmode=disable`,
            target: managed, anonymize: false, schemas: []
        }, dumpFile);

        expect(outcome.ok).toBe(false);
        const text = outcome.ok ? "" : outcome.lines.join("\n");
        expect(text).toContain(`Cannot connect to PostgreSQL at 127.0.0.1:${closed}`);
        expect(text).toContain("pg_dump said: connection to server");
        expect(text).toContain("Nothing was changed");
        expect(text).not.toContain("s3cret");
        expect(text).not.toContain("Command failed");
        expect(fs.existsSync(dumpFile)).toBe(false);
    });

    it("says so when the source refuses the credentials", async () => {
        const outcome = await dumpSource({
            source: `postgresql://rebase:wrong@127.0.0.1:${port}/source?sslmode=disable`,
            target: managed, anonymize: false, schemas: []
        }, path.join(work, "refused.dump"));

        const text = outcome.ok ? "" : outcome.lines.join("\n");
        expect(text).toContain(`Authentication failed for user "rebase" at 127.0.0.1:${port}`);
        expect(text).not.toContain("wrong");
    });

    it("finds a local database that is not there before reading the source", async () => {
        const closed = await findFreePort();

        const outcome = await dumpSource({
            source: url("source"),
            target: `postgresql://postgres@127.0.0.1:${closed}/postgres?sslmode=disable`,
            anonymize: false, schemas: []
        }, path.join(work, "no-target.dump"));

        const text = outcome.ok ? "" : outcome.lines.join("\n");
        expect(text).toContain(`Cannot connect to PostgreSQL at 127.0.0.1:${closed}`);
        expect(text).toContain("ECONNREFUSED");
        expect(text).toContain("the local database the pull would replace");
        expect(fs.existsSync(path.join(work, "no-target.dump"))).toBe(false);
    });
});
