/**
 * `rebase db pull` into the managed development database (PGlite), against a
 * real source Postgres in Docker.
 *
 * The default first-run setup is the managed database, and a pull into it
 * failed at the first `COPY`:
 *
 *     pg_restore: error: COPY failed for table "posts": ERROR:  unexpected EOF
 *     on client connection with an open transaction
 *
 * then "no connection to the server" for everything after it — and the daemon
 * stopped answering altogether, so the command hung on its next query and so
 * did every `rebase` command after it until the daemon was killed. PGlite's
 * socket server runs each protocol message on its own, so the `CopyData` that
 * follows `COPY … FROM stdin` never reaches the backend that is waiting for it.
 *
 * So the copy is compared with the same pull into a Postgres database: the
 * managed database must end up holding what Postgres holds.
 *
 * Needs Docker and the PostgreSQL client tools. A missing client fails the
 * suite rather than skipping it: a skipped suite reports a pass.
 */
import { execa } from "execa";
import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "fs";
import os from "os";
import path from "path";
import { fileURLToPath } from "url";
import pg from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { ensureManagedDatabase, stopManagedDatabase } from "./daemon";
import { dumpArgs, dumpEnv, dumpSource, findPgTool, restoreCopy, type PullPlan } from "./pull";
import { findFreePort } from "./state";

const HERE = path.dirname(fileURLToPath(import.meta.url));
/** Stands in for `bin/rebase.js`, which the daemon re-invokes: see `daemon.integration.test.ts`. */
const CLI_ENTRY = path.join(HERE, "__fixtures__", "cli-entry.ts");

const container = `${process.env.REBASE_E2E_CONTAINER_PREFIX || "rebase-pull-managed-it-"}${crypto.randomUUID().slice(0, 8)}`;
let port = "";
let work = "";
let project = "";
let managed = "";

/** A database's URL on the container, by name. */
const url = (database: string) => `postgresql://rebase:rebase@127.0.0.1:${port}/${database}?sslmode=disable`;

/**
 * One query on its own connection, with a deadline: a wedged PGlite does not
 * refuse a query, it never answers it.
 */
async function sql(connectionString: string, text: string): Promise<pg.QueryResult> {
    const client = new pg.Client({ connectionString, connectionTimeoutMillis: 10_000, query_timeout: 30_000 });
    client.on("error", () => undefined);
    await client.connect();
    try {
        return await client.query(text);
    } finally {
        await client.end().catch(() => undefined);
    }
}

/** The image whose major the local `pg_dump` can read: a client older than the server refuses it. */
async function imageForLocalClient(): Promise<string> {
    const version = await findPgTool("pg_dump");
    const major = Number(/(\d+)(\.\d+)*\s*(\(|$)/.exec(version ?? "")?.[1] ?? Number.NaN);
    if (!version || !Number.isInteger(major) || !(await findPgTool("pg_restore"))) {
        throw new Error("pg_dump and pg_restore are needed on PATH for this suite (e.g. `brew install libpq`).");
    }
    return major >= 18 ? "postgres:18-alpine" : `postgres:${major}-alpine`;
}

