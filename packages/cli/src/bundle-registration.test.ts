/**
 * `rebase build` writes the server-side `Database` registration before it
 * compiles, when the project asks for it.
 *
 * `registerDatabase: true` in `rebase.json` types `context.data` in collection
 * callbacks from the generated `Database`. The registration lives in
 * `config/generated/`, which is gitignored, and only `rebase generate-sdk` and
 * `rebase dev` wrote it. So a CI build of a fresh clone compiled the callbacks
 * against the untyped `context.data` and failed on the first typed column,
 * while the same project built locally. The bundle builder now writes it from
 * the collections, before the type check, for every command that builds a
 * bundle (`rebase build`, `rebase cloud deploy`).
 */
import fs from "fs";
import os from "os";
import path from "path";
import { createRequire } from "module";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { buildBundle } from "./bundle";

const require = createRequire(import.meta.url);

let scratch: string;

function write(relative: string, content: string): void {
    const file = path.join(scratch, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
}

const NOTES = "export default { slug: \"my-notes\", table: \"notes\", name: \"Notes\", " +
    "properties: { id: { type: \"string\", isId: true }, body: { type: \"string\", validation: { required: true } } } };\n";

beforeEach(() => {
    scratch = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "rebase-bundle-register-")));
    write("config/collections/my-notes.ts", NOTES);
    // The registration augments `@rebasepro/types`, so the compile needs one
    // that declares `Register` the way the real one does.
    write("node_modules/@rebasepro/types/package.json", JSON.stringify({ name: "@rebasepro/types", types: "index.d.ts" }));
    write("node_modules/@rebasepro/types/index.d.ts",
        "export interface Register {}\n" +
        "export type RegisteredDatabase = Register extends { database: infer DB } ? DB : unknown;\n");
    // This repository's TypeScript, not whatever `tsc` is on the PATH.
    fs.mkdirSync(path.join(scratch, "node_modules/.bin"), { recursive: true });
    fs.symlinkSync(require.resolve("typescript/bin/tsc"), path.join(scratch, "node_modules/.bin/tsc"));
    vi.spyOn(console, "log").mockImplementation(() => {});
});

afterEach(() => {
    fs.rmSync(scratch, { recursive: true, force: true });
    vi.restoreAllMocks();
});

/**
 * A config file that compiles only when `Register` holds the generated
 * `Database`: what a callback reading a typed column amounts to.
 */
const TYPED_PROBE =
    "import type { RegisteredDatabase } from \"@rebasepro/types\";\n" +
    "type Body = RegisteredDatabase extends { myNotes: { Row: { body: infer B } } } ? B : never;\n" +
    "export const body: Body = \"typed\";\n";

const build = (app: { type: "backend"; registerDatabase?: boolean }) =>
    buildBundle({ projectRoot: scratch, appName: "backend", app, runtimeRange: "^1" });

describe("the bundle builder and the Database registration", () => {
    it("writes it from the collections before compiling, when registerDatabase is set", async () => {
        // A fresh clone: no config/generated/. The probe compiles only once
        // the registration is there, so the build itself is the proof.
        write("config/probe.ts", TYPED_PROBE);

        await build({ type: "backend", registerDatabase: true });

        const register = fs.readFileSync(path.join(scratch, "config/generated/register.ts"), "utf-8");
        expect(register).toMatch(/^\/\/ Auto-generated by `rebase generate-sdk --register`/);
        expect(register).toContain("database: Database;");
        const types = fs.readFileSync(path.join(scratch, "config/generated/database.types.ts"), "utf-8");
        expect(types).toContain("myNotes");
    });

    it("writes nothing for a project that did not ask for it", async () => {
        await build({ type: "backend" });

        expect(fs.existsSync(path.join(scratch, "config/generated"))).toBe(false);
    });

    it("keeps a registration an earlier generate-sdk --register wrote current", async () => {
        write("config/generated/register.ts", "// Auto-generated by `rebase generate-sdk --register`. Do not edit.\n");
        write("config/generated/database.types.ts", "export type Database = {};\n");
        write("config/probe.ts", TYPED_PROBE);

        await build({ type: "backend" });

        expect(fs.readFileSync(path.join(scratch, "config/generated/database.types.ts"), "utf-8")).toContain("myNotes");
    });

    it("refuses to overwrite a register.ts the developer wrote", async () => {
        write("config/generated/register.ts", "// mine\nexport {};\n");

        await expect(build({ type: "backend", registerDatabase: true })).rejects.toThrow(/was not written by "rebase generate-sdk --register"/);

        expect(fs.readFileSync(path.join(scratch, "config/generated/register.ts"), "utf-8")).toBe("// mine\nexport {};\n");
    });
});
