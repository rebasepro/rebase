/**
 * The per-table `/api/admin/db` routes over real PostgreSQL (PGlite): catalog
 * details and the assembled definition, constraints, triggers, maintenance,
 * and the row browser's typed reads and writes.
 */
import { afterAll, beforeAll, describe, expect, it } from "@jest/globals";
import { PGlite } from "@electric-sql/pglite";
import type { SQLAdmin } from "@rebasepro/types";
import { createDbAdminRoutes } from "../../server/src/baas";
import { ensureBaasCatalogTables } from "../../server/src/baas";
import { buildRowsQuery, buildWhere } from "../../server/src/baas/db-table-rows";
import type { CatalogColumn } from "../../server/src/baas/db-table-catalog";
import { RLS_BOOTSTRAP_STATEMENTS } from "../src/schema/rls-bootstrap-sql";

function makePgliteSqlAdmin(db: PGlite): SQLAdmin {
    return {
        executeSql: async (sqlText: string, options?: { params?: unknown[] }) => {
            const res = await db.query<Record<string, unknown>>(sqlText, options?.params);
            return res.rows;
        },
        executeSqlTransaction: async (statements: readonly string[]) => {
            await db.exec("BEGIN");
            try {
                for (const stmt of statements) await db.query(stmt);
                await db.exec("COMMIT");
            } catch (err) {
                await db.exec("ROLLBACK").catch(() => undefined);
                throw err;
            }
        }
    };
}

interface Json { [key: string]: unknown }

describe("per-table /api/admin/db routes (PGlite)", () => {
    let db: PGlite;
    let app: ReturnType<typeof createDbAdminRoutes>;

    const call = async (method: string, path: string, body?: unknown): Promise<{ status: number; json: Json; text: string }> => {
        const res = await app.request(path, {
            method,
            headers: body === undefined ? undefined : { "Content-Type": "application/json" },
            body: body === undefined ? undefined : JSON.stringify(body)
        });
        const text = await res.text();
        let json: Json = {};
        try {
            json = JSON.parse(text) as Json;
        } catch {
            // CSV and other non-JSON bodies
        }
        return { status: res.status, json, text };
    };

    beforeAll(async () => {
        db = new PGlite();
        await db.waitReady;
        for (const statement of RLS_BOOTSTRAP_STATEMENTS) await db.exec(statement);
        const admin = makePgliteSqlAdmin(db);
        await ensureBaasCatalogTables(admin);
        await db.exec(`
            CREATE TABLE public.authors (
                id bigint PRIMARY KEY,
                name text NOT NULL
            );
            CREATE TABLE public.books (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                author_id bigint REFERENCES public.authors(id) ON DELETE CASCADE,
                title text NOT NULL,
                price numeric(30, 10),
                meta jsonb,
                tags text[],
                published_at timestamptz,
                status text DEFAULT 'draft',
                title_upper text GENERATED ALWAYS AS (upper(title)) STORED,
                CONSTRAINT books_price_positive CHECK (price >= 0)
            );
            CREATE INDEX books_title_idx ON public.books (title);
            COMMENT ON TABLE public.books IS 'Every book we''ve got';
            COMMENT ON COLUMN public.books.title IS 'Shown on the spine';
            ALTER TABLE public.books ENABLE ROW LEVEL SECURITY;
            CREATE POLICY books_read ON public.books FOR SELECT TO PUBLIC USING (true);
            CREATE FUNCTION public.touch_books() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
            CREATE TRIGGER books_touch BEFORE UPDATE ON public.books FOR EACH ROW EXECUTE FUNCTION public.touch_books();
            CREATE TABLE public.events (kind text, at timestamptz);
            CREATE MATERIALIZED VIEW public.book_counts AS SELECT author_id, count(*) AS n FROM public.books GROUP BY author_id;
            INSERT INTO public.authors VALUES (1, 'Ursula'), (2, 'Italo');
            INSERT INTO public.events VALUES ('boot', now());
        `);
        app = createDbAdminRoutes({
            admin,
            getServedTables: () => [],
            reloadSchema: async () => ({ tables: 0, revision: 1, unprotectedTables: [] })
        });
    });

    afterAll(async () => {
        await db.close();
    });

    it("lists foreign keys and row estimates with each table", async () => {
        const { status, json } = await call("GET", "/tables");
        expect(status).toBe(200);
        const tables = json.tables as Json[];
        const books = tables.find(t => t.name === "books");
        expect(books?.foreignKeys).toEqual([
            expect.objectContaining({
                fromTable: "books",
                fromColumns: ["author_id"],
                toTable: "authors",
                toColumns: ["id"],
                onDelete: "CASCADE"
            })
        ]);
        expect(tables.find(t => t.name === "book_counts")).toEqual(expect.objectContaining({ kind: "view", materialized: true }));
    });

    it("reads a table's details and assembles its definition", async () => {
        const { status, json } = await call("GET", "/tables/books/details");
        expect(status).toBe(200);
        const relation = json.relation as Json;
        expect(relation).toEqual(expect.objectContaining({ kind: "table", rlsEnabled: true, comment: "Every book we've got" }));

        const columns = json.columns as Json[];
        expect(columns.find(c => c.name === "id")).toEqual(expect.objectContaining({ identity: "by_default", primaryKey: true }));
        expect(columns.find(c => c.name === "price")).toEqual(expect.objectContaining({ type: "numeric(30,10)" }));
        expect(columns.find(c => c.name === "title_upper")).toEqual(expect.objectContaining({ generated: "stored" }));

        const constraints = json.constraints as Json[];
        expect(constraints.map(c => c.kind)).toEqual(expect.arrayContaining(["primary_key", "foreign_key", "check"]));

        const fks = json.foreignKeys as { outgoing: Json[]; incoming: Json[] };
        expect(fks.outgoing).toHaveLength(1);
        const authors = await call("GET", "/tables/authors/details");
        expect((authors.json.foreignKeys as { incoming: Json[] }).incoming[0]).toEqual(expect.objectContaining({ fromTable: "books" }));

        expect(json.triggers).toEqual([expect.objectContaining({ name: "books_touch", enabled: true, functionName: "touch_books" })]);
        expect(json.policies).toEqual([expect.objectContaining({ name: "books_read", command: "SELECT", using: "true" })]);
        expect((json.indexes as Json[]).find(i => i.name === "books_title_idx")).toEqual(expect.objectContaining({ backsConstraint: false }));

        const ddl = String(json.ddl);
        expect(ddl).toContain('CREATE TABLE "public"."books" (');
        expect(ddl).toContain('"id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL');
        expect(ddl).toContain('"title_upper" text GENERATED ALWAYS AS (upper(title)) STORED');
        expect(ddl).toContain('CONSTRAINT "books_price_positive" CHECK (price >= 0::numeric)');
        expect(ddl).toContain('ADD CONSTRAINT "books_author_id_fkey" FOREIGN KEY (author_id) REFERENCES authors(id) ON DELETE CASCADE;');
        expect(ddl).toContain("CREATE INDEX books_title_idx ON public.books USING btree (title);");
        expect(ddl).toContain('ALTER TABLE "public"."books" ENABLE ROW LEVEL SECURITY;');
        expect(ddl).toContain('CREATE POLICY "books_read" ON "public"."books"');
        expect(ddl).toContain("CREATE TRIGGER books_touch BEFORE UPDATE ON books");
        expect(ddl).toContain(`COMMENT ON TABLE "public"."books" IS 'Every book we''ve got';`);
        expect(ddl).not.toContain('"books_pkey" PRIMARY KEY (id);\nCREATE UNIQUE INDEX books_pkey');
        // NOT NULL is said once, on the column — not again as a Postgres 18 not-null constraint.
        expect(ddl).not.toMatch(/CONSTRAINT "books_\w+_not_null"/);
        expect(constraints.some(c => c.kind === "other")).toBe(false);

        const view = await call("GET", "/tables/book_counts/details");
        expect(String(view.json.ddl)).toContain('CREATE MATERIALIZED VIEW "public"."book_counts" AS');
    });

    it("answers 404 for a relation that does not exist", async () => {
        const { status } = await call("GET", "/tables/nope/details");
        expect(status).toBe(404);
    });

    it("inserts, reads, filters, sorts, pages, updates and deletes rows without losing precision", async () => {
        const inserted = await call("POST", "/tables/books/rows", {
            rows: [
                { author_id: "1", title: "The Dispossessed", price: "12345678901234567890.0123456789", meta: '{"isbn": "978-0"}', tags: "{sf,classic}", published_at: "1974-05-01T00:00:00Z" },
                { author_id: "2", title: "Invisible Cities", price: null },
                { author_id: "1", title: "The Lathe of Heaven", status: "published" }
            ]
        });
        expect(inserted.status).toBe(201);
        const rows = inserted.json.rows as Json[];
        expect(rows[0].price).toBe("12345678901234567890.0123456789");
        expect(rows[1].status).toBe("draft");
        expect(rows[0].title_upper).toBe("THE DISPOSSESSED");

        const page = await call("GET", `/tables/books/rows?orderBy=title&direction=desc&limit=2&offset=0`);
        expect(page.status).toBe(200);
        expect((page.json.rows as Json[]).map(r => r.title)).toEqual(["The Lathe of Heaven", "The Dispossessed"]);
        expect(page.json.count).toEqual({ value: 3, exact: true });
        expect(page.json.primaryKey).toEqual(["id"]);
        expect(page.json.readOnly).toBe(false);

        const filters = encodeURIComponent(JSON.stringify([
            { column: "author_id", op: "in", value: ["1"] },
            { column: "title", op: "ilike", value: "%heaven%" }
        ]));
        const filtered = await call("GET", `/tables/books/rows?filters=${filters}`);
        expect((filtered.json.rows as Json[]).map(r => r.title)).toEqual(["The Lathe of Heaven"]);

        const nulls = encodeURIComponent(JSON.stringify([{ column: "price", op: "is_null" }]));
        expect(((await call("GET", `/tables/books/rows?filters=${nulls}`)).json.rows as Json[])).toHaveLength(2);

        const gt = encodeURIComponent(JSON.stringify([{ column: "published_at", op: "gt", value: "1970-01-01" }]));
        expect(((await call("GET", `/tables/books/rows?filters=${gt}`)).json.rows as Json[])).toHaveLength(1);

        const target = rows[1];
        const updated = await call("PATCH", "/tables/books/rows", { key: { id: target.id }, values: { price: "9.5", meta: null } });
        expect(updated.status).toBe(200);
        expect((updated.json.row as Json).price).toBe("9.5000000000");

        const refused = await call("PATCH", "/tables/books/rows", { key: { id: target.id }, values: { title_upper: "X" } });
        expect(refused.status).toBe(400);

        const badType = await call("PATCH", "/tables/books/rows", { key: { id: target.id }, values: { price: "lots" } });
        expect(badType.status).toBe(400);
        expect(String((badType.json.error as Json | undefined)?.message ?? badType.text)).toContain("PostgreSQL refused");

        const deleted = await call("DELETE", "/tables/books/rows", { keys: [{ id: target.id }] });
        expect(deleted.json.deleted).toBe(1);
    });

    it("refuses an unknown column in filters and sort", async () => {
        const filters = encodeURIComponent(JSON.stringify([{ column: "nope", op: "eq", value: "1" }]));
        expect((await call("GET", `/tables/books/rows?filters=${filters}`)).status).toBe(400);
        expect((await call("GET", `/tables/books/rows?orderBy=${encodeURIComponent('title"; DROP TABLE books; --')}`)).status).toBe(400);
    });

    it("marks a table without a primary key read-only and refuses writes by key", async () => {
        const page = await call("GET", "/tables/events/rows");
        expect(page.json.readOnly).toBe(true);
        expect(page.json.readOnlyReason).toBe("no_primary_key");
        const update = await call("PATCH", "/tables/events/rows", { key: { kind: "boot" }, values: { kind: "x" } });
        expect(update.status).toBe(400);
    });

    it("streams the matching rows as CSV", async () => {
        const res = await app.request("/tables/authors/rows?format=csv&orderBy=id");
        expect(res.headers.get("content-type")).toContain("text/csv");
        expect(await res.text()).toBe("id,name\r\n1,Ursula\r\n2,Italo\r\n");
    });

    it("adds and drops constraints, toggles and drops triggers, runs maintenance and refreshes a materialized view", async () => {
        const preview = await call("POST", "/tables/authors/constraints", { kind: "unique", columns: ["name"], dryRun: true });
        expect(preview.json.statements).toEqual(['ALTER TABLE "public"."authors" ADD CONSTRAINT "authors_name_key" UNIQUE ("name");']);

        expect((await call("POST", "/tables/authors/constraints", { kind: "unique", columns: ["name"] })).status).toBe(201);
        expect((await call("POST", "/tables/authors/constraints", { kind: "check", name: "authors_name_len", expression: "length(name) > 0" })).status).toBe(201);
        expect((await call("POST", "/tables/authors/constraints", { kind: "check", expression: "true; DROP TABLE authors" })).status).toBe(400);
        const constraints = (await call("GET", "/tables/authors/details")).json.constraints as Json[];
        expect(constraints.map(c => c.name)).toEqual(expect.arrayContaining(["authors_name_key", "authors_name_len"]));
        expect((await call("DELETE", "/tables/authors/constraints/authors_name_len", {})).status).toBe(200);

        expect((await call("PATCH", "/tables/books/triggers/books_touch", { enabled: false })).status).toBe(200);
        const triggers = (await call("GET", "/tables/books/details")).json.triggers as Json[];
        expect(triggers[0].enabled).toBe(false);
        expect((await call("DELETE", "/tables/books/triggers/books_touch", {})).status).toBe(200);
        expect((await call("GET", "/tables/books/details")).json.triggers).toEqual([]);

        expect((await call("POST", "/tables/books/maintenance", { action: "analyze" })).status).toBe(200);
        expect((await call("POST", "/tables/books/maintenance", { action: "vacuum" })).status).toBe(200);
        expect((await call("POST", "/tables/books/maintenance", { action: "full" })).status).toBe(400);

        expect((await call("POST", "/tables/book_counts/refresh", {})).status).toBe(200);
        expect((await call("POST", "/tables/books/refresh", {})).status).toBe(400);
    });
});

describe("row query builder", () => {
    const column = (name: string, overrides: Partial<CatalogColumn> = {}): CatalogColumn => ({
        name,
        type: "text",
        udt: "text",
        category: "S",
        notNull: false,
        default: null,
        identity: null,
        generated: null,
        primaryKey: false,
        comment: null,
        ...overrides
    });
    const columns = [
        column("id", { type: "bigint", udt: "int8", category: "N", primaryKey: true }),
        column("meta", { type: "jsonb", udt: "jsonb", category: "U" }),
        column("doc", { type: "json", udt: "json", category: "U" }),
        column("tags", { type: "text[]", udt: "_text", category: "A" })
    ];

    it("casts each value to the column's own type, and compares json and arrays as text", () => {
        const params: unknown[] = [];
        const where = buildWhere([
            { column: "id", op: "gte", value: "10" },
            { column: "doc", op: "eq", value: "{}" },
            { column: "tags", op: "in", value: ["{a}"] },
            { column: "meta", op: "not_null" }
        ], columns, params);
        expect(where).toBe(
            ' WHERE "id" >= CAST($1 AS bigint) AND "doc"::text = $2 AND "tags"::text = ANY(CAST($3 AS text[])) AND "meta" IS NOT NULL'
        );
        expect(params).toEqual(["10", "{}", ["{a}"]]);
    });

    it("orders by the chosen column, then the primary key, and clamps the page size", () => {
        const { sql, params } = buildRowsQuery({
            schema: "public", table: "t", columns, filters: [], orderBy: "meta", direction: "desc", limit: 50_000, offset: -3
        });
        expect(sql).toContain('ORDER BY "meta" DESC NULLS LAST, "id" ASC LIMIT $1 OFFSET $2');
        expect(params).toEqual([1000, 0]);
    });
});
