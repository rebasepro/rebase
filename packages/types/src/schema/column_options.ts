/**
 * Validation of a temporal column. Bounds are ISO strings.
 *
 * @group Schema
 */
export interface DateValidation extends BaseValidation {
    /** Earliest accepted value. */
    min?: string | Date;
    /** Latest accepted value. */
    max?: string | Date;
}

/**
 * Validation of an array column.
 *
 * @group Schema
 */
export interface ArrayValidation extends BaseValidation {
    /** Fewest items accepted. */
    minItems?: number;
    /** Most items accepted. */
    maxItems?: number;
    /** Refuse an array holding the same value twice. */
    uniqueItems?: boolean;
    /**
     * For a JSON array of objects (`json.array(json.object({...}))`): refuse
     * two items with the same value in any one of these fields — each field
     * is unique across the items on its own (`["sku"]`: no SKU twice). The
     * fields are keys of the item object; anything else is refused when the
     * schema compiles.
     */
    uniqueBy?: string[];
}

/**
 * Every validation rule a column can carry, as stored on its definition and
 * served on the wire: patterns are strings, date bounds are ISO strings.
 *
 * @group Schema
 */
export interface ColumnValidation {
    /** The API error when a `.notNull()` column is missing from a create. */
    requiredMessage?: string;
    /**
     * Lower bound: minimum length of text, inclusive minimum of a number, earliest
     * accepted value of a temporal column (an ISO string).
     */
    min?: number | string;
    /**
     * Upper bound: maximum length of text, inclusive maximum of a number, latest
     * accepted value of a temporal column (an ISO string).
     */
    max?: number | string;
    /** Exact length of a text value. */
    length?: number;
    /** A pattern a text value must match: a `RegExp`'s source, its flags in `matchesFlags`. */
    matches?: string;
    /** Flags of `matches` (`"i"`, `"u"`, …). No flags when omitted. */
    matchesFlags?: string;
    /** The API error when `matches` fails. */
    matchesMessage?: string;
    /** A text value must be an e-mail address. */
    email?: boolean;
    /** A text value must be a URL. */
    url?: boolean;
    /** Lower-case a text value before it is stored. */
    lowercase?: boolean;
    /** Upper-case a text value before it is stored. */
    uppercase?: boolean;
    /** Trim surrounding whitespace from a text value before it is stored. */
    trim?: boolean;
    /** Exclusive upper bound of a number. */
    lessThan?: number;
    /** Exclusive lower bound of a number. */
    moreThan?: number;
    /** A number must be greater than zero. */
    positive?: boolean;
    /** A number must be less than zero. */
    negative?: boolean;
    /** A number must be a whole number. */
    integer?: boolean;
    /** Fewest items an array accepts. */
    minItems?: number;
    /** Most items an array accepts. */
    maxItems?: number;
    /** Refuse an array holding the same value twice. */
    uniqueItems?: boolean;
    /** Fields of a JSON array's object items, each unique across the items. See {@link ArrayValidation.uniqueBy}. */
    uniqueBy?: string[];
}

/** The rules a builder method accepts, before they are normalized. */
export type ValidationInput = StringValidation | NumberValidation | DateValidation | ArrayValidation | BaseValidation;

const isoOf = (value: string | Date): string => (value instanceof Date ? value.toISOString() : value);

/**
 * Validation rules in their stored form: a `RegExp` becomes its source and
 * flags, a `Date` bound becomes an ISO string. What a builder keeps is then
 * exactly what the wire carries.
 *
 * @group Schema
 */
export function normalizeValidation(rules: ValidationInput): ColumnValidation {
    const out: ColumnValidation = {};
    for (const [key, value] of Object.entries(rules)) {
        if (value === undefined) continue;
        if (key === "matches" && value instanceof RegExp) {
            out.matches = value.source;
            if (value.flags) out.matchesFlags = value.flags;
            continue;
        }
        if ((key === "min" || key === "max") && (value instanceof Date)) {
            out[key] = isoOf(value);
            continue;
        }
        // A list is copied, so the stored rules do not alias the caller's array.
        Object.assign(out, { [key]: Array.isArray(value) ? [...value] : value });
    }
    return out;
}

/**
 * How an image is resized before it is stored.
 *
 * @group Schema
 */
export interface StorageImageResize {
    /**
     * Largest width in pixels; a wider image is scaled down proportionally. No
     * width limit when omitted.
     */
    maxWidth?: number;
    /**
     * Largest height in pixels; a taller image is scaled down proportionally. No
     * height limit when omitted.
     */
    maxHeight?: number;
    /**
     * How the image fits `maxWidth` × `maxHeight`: `contain` (the default) scales
     * it to fit inside, keeping its aspect ratio; `cover` scales it to fill the box,
     * keeping its aspect ratio, and may crop.
     */
    mode?: "contain" | "cover";
    /** The stored image's format. `original` (the default) keeps the uploaded one. */
    format?: "original" | "jpeg" | "png" | "webp";
    /**
     * Quality of a lossy output (JPEG, WebP), 0–100: higher is sharper and larger.
     * 80 when omitted.
     */
    quality?: number;
}

