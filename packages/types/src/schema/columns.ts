/** `numeric` from either spelling: Drizzle's `(name?, { precision, scale, mode })` or the positional pair. */
function numericColumn(builder: string, first: unknown, second: unknown): ColumnBuilder<number, "numeric"> {
    let name: string | undefined;
    let precision: unknown;
    let scale: unknown;
    const positional = typeof first === "number" || (first === undefined && typeof second === "number");
    if (positional) {
        precision = first;
        scale = second;
    } else {
        [name] = typeof first === "string" ? [first] : [undefined];
        const config = configOf(typeof first === "string" ? second : first, builder);
        checkMode(config.mode, "number", DRIZZLE_REFUSALS.numericMode);
        precision = config.precision;
        scale = config.scale;
    }
    if (scale !== undefined && precision === undefined) {
        throw new Error(positional
            ? `\`col.${builder}(precision, scale)\`: a scale needs a precision.`
            : `\`col.${builder}({ precision, scale })\`: a scale needs a precision.`);
    }
    for (const [what, value] of [["precision", precision], ["scale", scale]] as const) {
        if (value !== undefined && (typeof value !== "number" || !Number.isInteger(value) || value < 0)) {
            throw new Error(`\`col.${builder}()\`: \`${what}\` is a whole number, got ${String(value)}.`);
        }
    }
    const type: ColumnType = typeof precision !== "number"
        ? { kind: "numeric" }
        : typeof scale !== "number" ? { kind: "numeric", precision } : { kind: "numeric", precision, scale };
    return new ColumnBuilder<number, "numeric">(namedDef(type, name, builder));
}

