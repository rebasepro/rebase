const DEFAULT_STRING_LENGTH = 255;

const lengthOf = (length: unknown, builder: string, positional = false): number => {
    const value = length ?? DEFAULT_STRING_LENGTH;
    if (typeof value !== "number" || !Number.isInteger(value) || value <= 0) {
        throw new Error(`\`col.${builder}(${positional ? "n" : "{ length }"})\` takes a positive whole number of characters, got ${String(length)}.`);
    }
    return value;
};

