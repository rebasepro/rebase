/**
 * The column builders, spelled as Drizzle's `pg-core` spells them: the
 * optional SQL column name first, then Drizzle's config object, then the
 * chain.
 *
 * ```ts
 * columns: {
 *     id:        col.uuid().primaryKey().defaultRandom(),
 *     title:     col.text().notNull().validate({ min: 3, max: 200 }),
 *     slug:      col.varchar({ length: 160 }).notNull().unique(),
 *     status:    postStatus().notNull().default("draft"),        // const postStatus = pgEnum("post_status", [...])
 *     tags:      col.text().array().notNull().default([]),
 *     heroImage: col.storage({ path: "posts/heroes/", accept: ["image/*"], maxBytes: "10MB" }),
 *     createdAt: col.timestamp({ withTimezone: true }).notNull().defaultNow(),
 * }
 * ```
 *
 * @group Schema
 */
