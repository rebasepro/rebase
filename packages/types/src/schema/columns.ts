/**
 * A Postgres enum type with a stated name, as Drizzle declares one: call it in
 * a column, `status: postStatus().notNull()`, or with the SQL column name,
 * `postStatus("state")`.
 *
 * @group Schema
 */
export interface PgEnum<V extends Labels> {
    /** A column of this enum type; the optional argument is the SQL column name. */
    (name?: string): ColumnBuilder<V[number], "enum">;
    /** The type's name in Postgres. */
    readonly enumName: string;
    /** Its labels, in order. */
    readonly enumValues: V;
}

/**
 * Declare a Postgres enum type by name, as Drizzle does:
 *
 * ```ts
 * export const postStatus = pgEnum("post_status", ["draft", "published"]);
 * // columns: { status: postStatus().notNull().default("draft") }
 * ```
 *
 * Every column of it shares the one type. Two declarations of the same name
 * must list the same labels.
 *
 * @group Schema
 */
export function pgEnum<const V extends Labels>(enumName: string, values: V): PgEnum<V>;
export function pgEnum(this: Refusal["pgEnumObject"], enumName: string, values: Readonly<Record<string, string>>): never;
export function pgEnum<const V extends Labels>(this: unknown, enumName: string, values: V | Readonly<Record<string, string>>): PgEnum<V> {
    if (typeof enumName !== "string" || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(enumName)) {
        throw new Error(`\`pgEnum(name, values)\`: the name is a plain SQL identifier, got ${JSON.stringify(enumName)}.`);
    }
    if (!isLabelTuple<V>(values)) throw new Error(DRIZZLE_REFUSALS.pgEnumObject);
    const labels = [...values];
    const factory = (name?: string): ColumnBuilder<V[number], "enum"> =>
        new ColumnBuilder<V[number], "enum">(namedDef({ kind: "enum", values: labels, name: enumName }, name, "enum"));
    return Object.assign(factory, { enumName, enumValues: values });
}

function isLabelTuple<V extends Labels>(values: V | Readonly<Record<string, string>>): values is V {
    return Array.isArray(values) && values.length > 0 && values.every(value => typeof value === "string");
}

/**
 * The type name `col.custom()` puts into DDL: trimmed, and refused when it is
 * empty or could end the statement it is written into.
 */
function customSqlType(sqlType: string): string {
    const trimmed = typeof sqlType === "string" ? sqlType.trim() : "";
    if (trimmed.length === 0) throw new Error("`col.custom()` takes the Postgres type, e.g. `col.custom({ dataType: \"inet\" })`.");
    if (/;|--|\/\*/.test(trimmed)) {
        throw new Error(`\`col.custom(${JSON.stringify(sqlType)})\`: a type name holds no \`;\` and no comment.`);
    }
    return trimmed;
}

/**
 * Whether a value is a column builder, from this copy of the package or
 * another.
 *
 * @group Schema
 */
export function isColumnBuilder(value: unknown): value is AnyColumn {
    return typeof value === "object" && value !== null && "brand" in value && value.brand === COLUMN_BRAND;
}
