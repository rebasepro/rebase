/** `varchar` / `char`, from either spelling: Drizzle's `(name?, { length, enum? })` or the positional length. */
function stringColumn<K extends "varchar" | "char">(kind: K, first: unknown, second: unknown): ColumnBuilder<string, K> {
    if (first === undefined || typeof first === "number") {
        return new ColumnBuilder<string, K>(baseDef(kind === "varchar"
            ? { kind: "varchar", length: lengthOf(first, kind, true) }
            : { kind: "char", length: lengthOf(first, kind, true) }));
    }
    const name = typeof first === "string" ? first : undefined;
    const raw = typeof first === "string" ? second : first;
    if (raw === undefined) throw new Error(kind === "varchar" ? DRIZZLE_REFUSALS.varcharLength : DRIZZLE_REFUSALS.charLength);
    const config = configOf(raw, kind);
    if (config.length === undefined) throw new Error(kind === "varchar" ? DRIZZLE_REFUSALS.varcharLength : DRIZZLE_REFUSALS.charLength);
    const length = lengthOf(config.length, kind);
    const def = namedDef(kind === "varchar" ? { kind: "varchar", length } : { kind: "char", length }, name, kind);
    if (config.enum !== undefined) def.oneOf = labelsOf(config.enum, `\`col.${kind}({ enum })\``);
    return new ColumnBuilder<string, K>(def);
}

