/** The SQL column name a builder's leading argument gives, checked. */
function sqlName(name: string | undefined, builder: string): string | undefined {
    if (name === undefined) return undefined;
    if (typeof name !== "string" || name.length === 0) {
        throw new Error(`\`col.${builder}(name, …)\`: the leading argument is the SQL column name, a non-empty string.`);
    }
    return name;
}

/** A fresh definition, named by the builder's leading argument when it has one. */
function namedDef(type: ColumnType, name: string | undefined, builder: string): ColumnDef {
    const def = baseDef(type);
    const column = sqlName(name, builder);
    if (column !== undefined) def.column = column;
    return def;
}

/** Drizzle's `(name?, config?)` arguments, either of which may be left out. */
function nameAndConfig<C>(first: string | C | undefined, second: C | undefined): [string | undefined, C | undefined] {
    return typeof first === "string" ? [first, second] : [undefined, first];
}

/** A config object, checked at run time: JavaScript callers bypass the types. */
function configOf(value: unknown, builder: string): Record<string, unknown> {
    if (value === undefined) return {};
    if (typeof value !== "object" || value === null || Array.isArray(value)) {
        throw new Error(`\`col.${builder}()\` takes an optional SQL column name and a config object, got ${JSON.stringify(value)}.`);
    }
    return { ...value };
}

/** The definition of an array of `item`: what `col.text().array()` and `col.array(col.text())` build. */
function arrayDef(item: ColumnDef): ColumnDef {
    if (item.type.kind === "array") throw new Error(DRIZZLE_REFUSALS.arrayOfArray);
    const def = baseDef({ kind: "array", of: item.type });
    def.element = item;
    if (item.storage) def.storage = item.storage;
    return def;
}

/** A list of string labels: an enum's values, Drizzle's `{ enum: [...] }`. */
function labelsOf(values: unknown, where: string): string[] {
    if (!Array.isArray(values) || values.length === 0 || values.some(value => typeof value !== "string")) {
        throw new Error(`${where} takes a non-empty list of strings, got ${JSON.stringify(values)}.`);
    }
    return values.filter((value): value is string => typeof value === "string");
}

